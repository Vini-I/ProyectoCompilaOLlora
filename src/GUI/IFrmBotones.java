    private void btnDirIzqActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDirIzqActionPerformed
        if (!dirIzq.isActiva()) {
            if (dirDer.isActiva()) {
                dirDer.desactivar();
                dash.getLblDerechaOn().setEnabled(false);
            }
            dirIzq.activar();
            dash.getLblIzquierdaOn().setEnabled(true);
            tempDir.stop();
            tempDir.start();
        } else {
            dirIzq.desactivar();
            dash.getLblIzquierdaOn().setEnabled(false);
            tempDir.stop();
        }
    }//GEN-LAST:event_btnDirIzqActionPerformed

    private void btnEmerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEmerActionPerformed
        if (!emergencia) {
            this.emergencia = true;
            dirDer.desactivar();
            dash.getLblDerechaOn().setEnabled(false);
            dirIzq.desactivar();
            dash.getLblIzquierdaOn().setEnabled(false);
            
            dirIzq.activar();
            dash.getLblIzquierdaOn().setEnabled(true);
            dirDer.activar();
            dash.getLblDerechaOn().setEnabled(true);
            tempDir.stop();
            tempDir.start();
        } else {
            this.emergencia = false;
            dirIzq.desactivar();
            dash.getLblIzquierdaOn().setEnabled(false);
            dirDer.desactivar();
            dash.getLblDerechaOn().setEnabled(false);
            tempDir.stop();
        }
    }//GEN-LAST:event_btnEmerActionPerformed

    private void btnDirDerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDirDerActionPerformed
        if (!dirDer.isActiva()) {
            if (dirIzq.isActiva()) {
                dirIzq.desactivar();
                dash.getLblIzquierdaOn().setEnabled(false);
            }
            dirDer.activar();
            dash.getLblDerechaOn().setEnabled(true);
            tempDir.stop();
            tempDir.start();
        } else {
            dirDer.desactivar();
            dash.getLblDerechaOn().setEnabled(false);
            tempDir.stop();
        }
    }//GEN-LAST:event_btnDirDerActionPerformed

    private void tglBtnAltaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tglBtnAltaActionPerformed
        if (!luz.isIntensidadLuz()) {
            tglBtnBaja.setSelected(false);
            luz.cambiarIntensidad();
            if (luz.isActiva()) {
                dash.getLblLuzBaja().setEnabled(false);
                dash.getLblLuzAlta().setEnabled(true);
            }
        }
    }//GEN-LAST:event_tglBtnAltaActionPerformed

    private void tglBtnBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tglBtnBajaActionPerformed
        if (luz.isIntensidadLuz()) {
            tglBtnAlta.setSelected(false);
            luz.cambiarIntensidad();
            if (luz.isActiva()) {
                dash.getLblLuzAlta().setEnabled(false);
                dash.getLblLuzBaja().setEnabled(true);
            }
        }
    }//GEN-LAST:event_tglBtnBajaActionPerformed

    private void tglBtnLucesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tglBtnLucesActionPerformed
        if (!luz.isActiva()) {
            luz.activar();
            if (!luz.isIntensidadLuz()) dash.getLblLuzBaja().setEnabled(true);
            else dash.getLblLuzAlta().setEnabled(true);
        } else {
            luz.desactivar();
            if (!luz.isIntensidadLuz()) dash.getLblLuzBaja().setEnabled(false);
            else dash.getLblLuzAlta().setEnabled(false);
        }
    }//GEN-LAST:event_tglBtnLucesActionPerformed

    private void tglBtnLeftSeatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tglBtnLeftSeatActionPerformed
       if (!cintuIzq.isPuesto()) {
           cintuIzq.poner();
           dash.getLblSeatbeltD().setEnabled(true);
       } else {
           cintuIzq.quitar();
           dash.getLblSeatbeltD().setEnabled(false);
       }
    }//GEN-LAST:event_tglBtnLeftSeatActionPerformed

